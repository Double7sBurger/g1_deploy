"""One definition of the sim-to-sim benchmark, shared by the Isaac Lab and MuJoCo runners.

Every quantity that could differ between the two sides and change the answer lives here and only
here: which commands are issued and when, what the initial pose is, when an episode counts as
failed, and how tracking error is scored. The runners are reduced to "step your simulator, record
these arrays"; nothing they do can silently make one side easier than the other.

**Two suites.** ``hold`` sweeps a command grid, one command held for a whole episode, which gives a
per-command success rate and a tracking-error map. ``sequence`` reproduces what training actually
does -- a fresh draw from :class:`UniformVelocityCommand`'s distribution every 10 s, with the yaw
element generated by the same heading controller -- which is the realistic case but averages over
regimes. Both are run on both sides.

**The yaw command is not an input.** This task trains with ``heading_command=True`` and
``rel_heading_envs=1.0``, so the third element of the command is a proportional controller on
heading error, recomputed every control step. The protocol therefore carries a *heading target*, and
each runner derives the yaw rate from its own measured heading with the same gain and clip.

.. attention::
    The two simulators do not start from the same root height, because the two robot descriptions do
    not agree on the robot: the USD's trunk is 3.3 kg lighter than the MJCF's and the USD has no
    waist roll/pitch. Each side places itself the way its own description says to and the policy runs
    from step 0; see :data:`SETTLE_S` for why the obvious fix -- holding the default pose first --
    is not available.
"""

from __future__ import annotations

import zlib

import numpy as np

CONTROL_DT = 0.02
"""Policy period [s]; must match ``g1_deploy_core.CONTROL_DT``."""

SETTLE_S = 0.0
"""Seconds of zero action before the policy is engaged. Zero, deliberately.

A settle phase was the obvious way to erase the two sides' different spawn heights, and it does not
work: **the G1 cannot hold its own default pose without the policy.** Stepping the stock task with
zero actions -- which commands exactly ``default_joint_pos`` -- the pelvis goes 0.738 m to 0.626 m in
half a second and projected gravity reaches -0.649 by 1.5 s, with the contact termination firing on
the way. The default pose is a slight crouch that the shipped gains do not statically support.

So the policy is engaged from step 0, which is also what training does: every episode there begins
with the policy already running. The residual spawn-height difference (Isaac Lab 0.738 m from
``G1_CFG.init_state``, MuJoCo 0.775 m from resting the lowest geom on the floor) is not an artifact
to be washed out -- it is the two descriptions disagreeing about the robot's leg geometry, and
:mod:`benchmark_report` prints both so it stays visible.
"""

EPISODE_S = 15.0
"""Scored seconds per episode, after the settle."""

RESAMPLE_S = 10.0
"""Command resampling period in the ``sequence`` suite [s]; training's value."""

FALL_GRAVITY_Z = -0.7
"""Projected-gravity z above which the robot counts as fallen; the same rule on both sides."""

JOINT_JITTER_RAD = 0.01
"""Per-seed initial joint perturbation [rad], so a suite entry is not a single sample."""

TRACK_STD = 0.5
"""``sqrt(0.25)`` -- the exponential-kernel width of ``track_lin_vel_xy_exp`` in training."""

HOLD_GRID = tuple((vx, vy) for vx in (0.0, 0.25, 0.5, 0.75, 1.0) for vy in (-0.5, 0.0, 0.5))
"""Commands held for a whole episode in the ``hold`` suite."""

# Draws matching UniformVelocityCommandCfg for this task.
_LIN_VEL_X = (0.0, 1.0)
_LIN_VEL_Y = (-0.5, 0.5)
_HEADING = (-np.pi, np.pi)
_REL_STANDING = 0.15


DEMO_SCHEDULE = (
    # (duration [s], vx [m/s], vy [m/s], heading target [deg], caption)
    (4.0, 0.5, 0.0, 0.0, "forward 0.5 m/s"),
    (4.0, 1.0, 0.0, 0.0, "forward 1.0 m/s"),
    (4.0, 0.0, 0.5, 0.0, "strafe left 0.5 m/s"),
    (4.0, 0.5, 0.0, 90.0, "forward + turn to +90 deg"),
    (4.0, 0.0, 0.0, 90.0, "stand"),
)
"""Command steps for the side-by-side recordings, shared so both simulators get the identical input.

Steps rather than ramps: training's command generator resamples every 10 s and never interpolates,
so a step is in distribution and a smooth ramp would be the unusual input.
"""


def demo_command(elapsed: float) -> tuple[float, float, float, str]:
    """Scheduled ``(vx, vy, heading [rad], caption)`` at ``elapsed`` seconds of :data:`DEMO_SCHEDULE`."""
    boundary = 0.0
    for duration, vx, vy, heading_deg, caption in DEMO_SCHEDULE:
        boundary += duration
        if elapsed < boundary:
            return vx, vy, float(np.deg2rad(heading_deg)), caption
    _, vx, vy, heading_deg, caption = DEMO_SCHEDULE[-1]
    return vx, vy, float(np.deg2rad(heading_deg)), caption


def demo_duration() -> float:
    """Total length of :data:`DEMO_SCHEDULE` [s]."""
    return sum(step[0] for step in DEMO_SCHEDULE)


class Episode:
    """One benchmark episode: a fixed initial perturbation and a fixed command schedule.

    Both runners build the identical object from the same ``(suite, index)``, so any difference in
    the result is a difference between the simulators.
    """

    def __init__(self, suite: str, index: int):
        """Build episode ``index`` of ``suite``.

        Args:
            suite: ``"hold"`` or ``"sequence"``.
            index: Episode number within the suite.

        Raises:
            ValueError: If the suite name is unknown.
        """
        self.suite = suite
        self.index = index
        # Seeded off the suite name too, so hold episode 3 and sequence episode 3 are not twins.
        # crc32 rather than hash(): the two runners are separate processes and Python randomizes
        # string hashing per process, which would hand them different command schedules.
        rng = np.random.default_rng(zlib.crc32(f"{suite}:{index}".encode()))

        if suite == "hold":
            vx, vy = HOLD_GRID[index % len(HOLD_GRID)]
            self.segments = [(float(vx), float(vy), 0.0, False)]
        elif suite == "sequence":
            self.segments = []
            for _ in range(int(np.ceil(EPISODE_S / RESAMPLE_S))):
                standing = bool(rng.uniform() <= _REL_STANDING)
                self.segments.append(
                    (
                        float(rng.uniform(*_LIN_VEL_X)),
                        float(rng.uniform(*_LIN_VEL_Y)),
                        float(rng.uniform(*_HEADING)),
                        standing,
                    )
                )
        else:
            raise ValueError(f"unknown suite {suite!r}; expected 'hold' or 'sequence'")

    def joint_jitter(self, joint_names: list[str]) -> np.ndarray:
        """Initial joint offset [rad] for the given joint order.

        Drawn per joint *name* from one stream in a fixed name order, so the two sides perturb the
        same physical joints by the same amount even though their joint indexing differs.

        Args:
            joint_names: Joint order to return the offsets in.

        Returns:
            Offsets aligned with ``joint_names``, shape ``(len(joint_names),)``.
        """
        canonical = sorted(joint_names)
        # A fresh generator per call, so the offsets do not depend on how often this is asked for.
        rng = np.random.default_rng(zlib.crc32(f"jitter:{self.suite}:{self.index}".encode()))
        by_name = dict(zip(canonical, rng.normal(0.0, JOINT_JITTER_RAD, len(canonical))))
        return np.array([by_name[n] for n in joint_names], dtype=np.float32)

    def planar_command(self, step: int) -> tuple[float, float, float, bool]:
        """Command for control step ``step`` (0 is the first scored step).

        Returns:
            ``(vx, vy, heading_target, standing)`` -- linear velocities in [m/s], heading in [rad].
            A standing segment reports zeros and the runner must also zero the yaw rate, which is
            what ``UniformVelocityCommand._update_command`` does.
        """
        seg = min(int(step * CONTROL_DT // RESAMPLE_S), len(self.segments) - 1)
        vx, vy, heading, standing = self.segments[seg]
        return (0.0, 0.0, heading, True) if standing else (vx, vy, heading, False)


def num_episodes(suite: str, repeats: int) -> int:
    """Episode count for a suite run with ``repeats`` seeds per grid entry."""
    return len(HOLD_GRID) * repeats if suite == "hold" else repeats


def score(record: dict) -> dict:
    """Reduce one episode's recorded arrays to comparable numbers.

    Args:
        record: Arrays keyed ``cmd`` ``(T, 3)``, ``lin_vel_b`` ``(T, 3)``, ``ang_vel_b`` ``(T, 3)``,
            ``gravity_z`` ``(T,)``, ``root_z`` ``(T,)``, all at :data:`CONTROL_DT` and starting after
            the settle. Shorter than the full episode means the run ended early.

    Returns:
        Per-episode metrics. ``success`` is 1.0 only if the robot never fell *and* the record runs
        the full :data:`EPISODE_S`.
    """
    grav = np.asarray(record["gravity_z"], dtype=np.float64)
    n_full = int(round(EPISODE_S / CONTROL_DT))
    fell = np.flatnonzero(grav > FALL_GRAVITY_Z)
    alive_n = int(fell[0]) if len(fell) else len(grav)

    cmd = np.asarray(record["cmd"], dtype=np.float64)[:alive_n]
    lin = np.asarray(record["lin_vel_b"], dtype=np.float64)[:alive_n]
    ang = np.asarray(record["ang_vel_b"], dtype=np.float64)[:alive_n]
    lin_err = np.linalg.norm(lin[:, :2] - cmd[:, :2], axis=1) if alive_n else np.array([np.nan])
    ang_err = np.abs(ang[:, 2] - cmd[:, 2]) if alive_n else np.array([np.nan])

    return {
        "success": float(alive_n >= n_full and len(grav) >= n_full),
        "survival_s": alive_n * CONTROL_DT,
        "lin_vel_err": float(np.mean(lin_err)),
        "ang_vel_err": float(np.mean(ang_err)),
        "lin_track_score": float(np.mean(np.exp(-(lin_err**2) / TRACK_STD**2))),
        "ang_track_score": float(np.mean(np.exp(-(ang_err**2) / TRACK_STD**2))),
        "root_z": float(np.mean(np.asarray(record["root_z"])[:alive_n])) if alive_n else np.nan,
        "cmd_speed": float(np.linalg.norm(cmd[0, :2])) if alive_n else np.nan,
    }
